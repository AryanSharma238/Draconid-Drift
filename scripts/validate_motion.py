"""M5: real-data proper-motion validation (Task 08 M5).

Runs frames -> pass_stack -> refine_registration -> motion_search -> measure_movers on the real
SPHEREx frames for the high-PM test targets, picks the mover nearest the target, and compares it
with tests/data/reference_pm.json. Writes notes/motion_validation.md.

python scripts/validate_motion.py            # needs the S3 footprint index (run on the EC2 box)
"""

import asyncio
import json
import math
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from targets import propagate

from backend import index, motion
from backend.fetch import get_frames
from backend.models import make_grid

RUNS = [("wise0855", 6), ("barnard", 6), ("barnard", 3), ("epsindb", 6)]  # per M5 spec
SIZE_DEG = 0.1
ACCEPT_SIGMA = 3.0  # M5 acceptance: |delta| < 3 sigma ...
ACCEPT_ARCSEC_YR = 1.5  # ... or < 1.5"/yr
OUT = ROOT / "notes" / "motion_validation.md"


async def run_one(key: str, det: int, ref: dict) -> dict:
    ra, dec = propagate(key)
    grid = make_grid(ra, dec, SIZE_DEG)
    refs = await index.find_images(grid.ra, grid.dec, det)
    frames, failed = [], 0
    async for _i, frame, _err in get_frames(refs, grid):
        if frame is None:
            failed += 1
        else:
            frames.append(frame)
    passes = motion.refine_registration(motion.pass_stack(frames))
    t = time.perf_counter()
    mmap = motion.motion_search(passes)
    search_ms = (time.perf_counter() - t) * 1000
    movers = motion.measure_movers(passes, mmap, grid)
    row = {
        "target": key,
        "det": det,
        "n_frames": len(frames),
        "failed": failed,
        "n_pass": len(passes),
        "reg": [(round(p.dx, 2), round(p.dy, 2)) for p in passes],
        "n_movers": len(movers),
        "search_ms": search_ms,
        "ref": ref,
        "found": None,
    }
    if not movers:
        return row
    cosd = math.cos(math.radians(grid.dec))
    sep = [math.hypot((m.ra0 - grid.ra) * cosd, m.dec0 - grid.dec) * 3600 for m in movers]
    best = movers[sep.index(min(sep))]
    d_ra = (best.pmra_masyr - ref["pmra_masyr"]) / 1000
    d_de = (best.pmdec_masyr - ref["pmdec_masyr"]) / 1000
    sig_ra = abs(d_ra) / (best.epmra_masyr / 1000) if best.epmra_masyr > 0 else float("inf")
    sig_de = abs(d_de) / (best.epmdec_masyr / 1000) if best.epmdec_masyr > 0 else float("inf")
    ok = all(s < ACCEPT_SIGMA or abs(d) < ACCEPT_ARCSEC_YR for s, d in ((sig_ra, d_ra), (sig_de, d_de)))
    row["found"] = {"sep_arcsec": min(sep), "m": best, "d": (d_ra, d_de), "sig": (sig_ra, sig_de), "ok": ok}
    return row


def fmt(r: dict) -> str:
    ref = r["ref"]
    refs = f"{ref['pmra_masyr'] / 1000:+.2f}, {ref['pmdec_masyr'] / 1000:+.2f}"
    head = f"| {r['target']} | {r['det']} | {r['n_pass']} | "
    if r["found"] is None:
        return head + f"NOT FOUND | — | {refs} | — | {r['search_ms']:.0f} | {r['n_movers']} | FAIL |"
    f, m = r["found"], r["found"]["m"]
    return (
        head + f"{m.pmra_masyr / 1000:+.2f} ± {m.epmra_masyr / 1000:.2f} | "
        f"{m.pmdec_masyr / 1000:+.2f} ± {m.epmdec_masyr / 1000:.2f} | {refs} | "
        f"{f['sig'][0]:.1f}, {f['sig'][1]:.1f} | {r['search_ms']:.0f} | {r['n_movers'] - 1} | "
        f"{'PASS' if f['ok'] else 'FAIL'} (sep {f['sep_arcsec']:.0f}″) |"
    )


async def main() -> None:
    refs = json.loads((ROOT / "tests" / "data" / "reference_pm.json").read_text())
    rows = [await run_one(k, d, refs[k]) for k, d in RUNS]
    lines = [
        "# M5 real-data motion validation",
        "",
        (
            f"Generated by `scripts/validate_motion.py`, {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}. "
            f"FOV {SIZE_DEG}°. PM in ″/yr (pmra includes cos δ). Reference: `tests/data/reference_pm.json`. "
            f"Acceptance: |Δ| < {ACCEPT_SIGMA}σ or < {ACCEPT_ARCSEC_YR}″/yr on both axes."
        ),
        "",
        (
            "| target | det | n_pass | measured pmra ± | measured pmdec ± | reference | Δ/σ (ra, dec) "
            "| grid-search ms | other candidates | result |"
        ),
        "|---|---|---|---|---|---|---|---|---|---|",
        *[fmt(r) for r in rows],
        "",
        "Registration offsets per pass (dx, dy px) and frames used:",
        "",
        *[
            f"- {r['target']} D{r['det']}: {r['reg']}, frames {r['n_frames']} (failed {r['failed']})"
            for r in rows
        ],
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    asyncio.run(main())
