def propagate(key: str, epoch_jyear: float = TARGET_EPOCH_JYEAR) -> tuple[float, float]:
    ra, dec, pmra, pmdec, _ = CATALOG[key]
    c = SkyCoord(
        ra=ra * u.deg,
        dec=dec * u.deg,
        pm_ra_cosdec=pmra * u.mas / u.yr,
        pm_dec=pmdec * u.mas / u.yr,
        obstime=Time(2000.0, format="jyear"),
        frame="icrs",
    )
    p = c.apply_space_motion(new_obstime=Time(epoch_jyear, format="jyear"))
    return float(p.ra.deg), float(p.dec.deg)


